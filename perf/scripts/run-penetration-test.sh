#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PERF_DIR="${SCRIPT_DIR}/.."
RESULTS_DIR="${PERF_DIR}/jmeter/results/penetration_$(date +%Y%m%d_%H%M%S)"

# Locate JMeter
if command -v jmeter >/dev/null 2>&1; then
    JMETER_BIN="jmeter"
elif [ -x "/Users/fme849/Personal/Opensource/apache-jmeter-5.6.3/bin/jmeter" ]; then
    JMETER_BIN="/Users/fme849/Personal/Opensource/apache-jmeter-5.6.3/bin/jmeter"
else
    echo "ERROR: JMeter binary not found. Please ensure JMeter is installed." >&2
    exit 1
fi

export JVM_ARGS="${JVM_ARGS:--Xms1g -Xmx4g}"

THREADS="${1:-150}"
DURATION="${2:-60}"
RAMPUP="${3:-15}"

echo "=========================================================================="
echo "   TinyLink DDoS Cache Penetration & High Availability Stress Test        "
echo "=========================================================================="
echo "Configuration:"
echo " - Penetration Threads : ${THREADS}"
echo " - Test Duration       : ${DURATION}s"
echo " - Ramp-up Time        : ${RAMPUP}s"
echo " - Results Output      : ${RESULTS_DIR}"
echo ""

# 1. Health check backend
echo ">>> [1/4] Verifying TinyLink backend on port 8080..."
if ! curl -s -o /dev/null -w "%{http_code}" http://localhost:8080/swagger-ui.html | grep -q "200\|302\|404"; then
    echo "ERROR: TinyLink application is not responding on http://localhost:8080." >&2
    echo "Please start the app in another terminal using:" >&2
    echo "    ./mvnw spring-boot:run -Dspring-boot.run.profiles=perf" >&2
    exit 1
fi
echo "Backend is alive!"

# 2. Redis initial key count
INIT_REDIS_KEYS=$(docker exec tinylink_redis_perf redis-cli dbsize 2>/dev/null || echo "0")
echo ">>> [2/4] Redis initial key count: ${INIT_REDIS_KEYS}"

# 3. Execute JMeter
mkdir -p "${RESULTS_DIR}"
echo ">>> [3/4] Launching DDoS Cache Penetration attack..."

"${JMETER_BIN}" -n \
    -t "${PERF_DIR}/jmeter/cache_penetration_ddos.jmx" \
    -l "${RESULTS_DIR}/penetration_run.jtl" \
    -e -o "${RESULTS_DIR}/dashboard" \
    -Jhost=localhost \
    -Jport=8080 \
    -Jthreads="${THREADS}" \
    -Jrampup="${RAMPUP}" \
    -Jduration="${DURATION}"

# 4. Post-run metrics
FINAL_REDIS_KEYS=$(docker exec tinylink_redis_perf redis-cli dbsize 2>/dev/null || echo "0")
DIFF_KEYS=$((FINAL_REDIS_KEYS - INIT_REDIS_KEYS))

echo ""
echo "=========================================================================="
echo ">>> [4/4] Attack Completed! Post-Attack Telemetry Summary:"
echo "=========================================================================="
echo " - Redis keys generated by penetration: +${DIFF_KEYS} keys"
echo " - HTML Dashboard: file://${RESULTS_DIR}/dashboard/index.html"
echo "=========================================================================="
